#!/usr/bin/env bash
# Give the application commit currently referenced by DEV a QA release tag.
#
# Usage (run from the application repository root):
#   RELEASE_VERSION=1.2.0 bash ci/release/create-next-tag.sh \
#     reports/source-environment.env reports/qa-release.env
#
# Legacy standalone tag allocator; tag-based promotion does not call this script.
# Required environment: RELEASE_VERSION and APP_REPO_ACCESS_TOKEN (tag push).
# Input file: trusted shell assignments for SOURCE_COMMIT and SOURCE_IMAGE_DIGEST.
# Output file: RELEASE_TAG, SOURCE_COMMIT, and SOURCE_IMAGE_DIGEST assignments.
# Flow: read DEV state -> verify ancestry -> reuse/allocate beta tag -> push tag.
#
# This is release bookkeeping: it does not build, copy, or deploy an ECR image.
# Git history is needed for the ancestry check below, not for deploying a digest.

# Fail on command errors, unset variables, and failed commands inside pipelines.
set -euo pipefail

# 1. Load the DEV state and validate the requested base version.
STATE_FILE="${1:?source state file is required}"
OUTPUT_FILE="${2:?output file is required}"

: "${RELEASE_VERSION:?RELEASE_VERSION is required}"
: "${APP_REPO_ACCESS_TOKEN:?APP_REPO_ACCESS_TOKEN is required}"

if [[ ! -f "${STATE_FILE}" ]]; then
  echo "ERROR: Source state file not found: ${STATE_FILE}"
  exit 1
fi

# source executes shell assignments; this must be the file generated by CI.
source "${STATE_FILE}"

: "${SOURCE_COMMIT:?SOURCE_COMMIT is required}"
: "${SOURCE_IMAGE_DIGEST:?SOURCE_IMAGE_DIGEST is required}"

# Accept a numeric major.minor.patch base; this script adds "v" and "-beta.N".
VERSION_PATTERN='^[0-9]+\.[0-9]+\.[0-9]+$'

if [[ ! "${RELEASE_VERSION}" =~ ${VERSION_PATTERN} ]]; then
  echo "ERROR: RELEASE_VERSION must use semantic version format."
  echo "Example: 1.2.0"
  exit 1
fi

# 2. Fetch the tags used for numbering and enough history to verify ancestry.
# QA requests a full clone, but this fallback also supports shallow checkouts.
FETCH_OPTIONS=(--tags)
if [[ "$(git rev-parse --is-shallow-repository)" == "true" ]]; then
  FETCH_OPTIONS+=(--unshallow)
fi
# The explicit refspec refreshes origin/main even when CI checked out a different
# branch. Its leading '+' permits updating that local tracking ref; it does not
# force-push main or overwrite existing release tags.
git fetch "${FETCH_OPTIONS[@]}" origin '+refs/heads/main:refs/remotes/origin/main'

# Require the DEV application commit to be reachable from application main.
if ! git merge-base --is-ancestor "${SOURCE_COMMIT}" origin/main; then
  echo "ERROR: DEV deployed commit is not contained in origin/main."
  exit 1
fi

# 3. Reuse a tag for this version and commit, or choose the next beta number.
# Example: existing v1.2.0-beta.1 and .2 -> v1.2.0-beta.3 for a new commit.
TAG_PREFIX="v${RELEASE_VERSION}-beta."
NEXT_NUMBER=1

# The process substitution at the end feeds the loop without a pipe/subshell,
# so NEXT_NUMBER survives the loop. sort -V orders beta.2 before beta.10 on Linux.
while IFS= read -r TAG; do
  [[ -z "${TAG}" ]] && continue

  # Resolve either an annotated or lightweight tag to its application commit.
  TAG_COMMIT="$(git rev-list -n 1 "${TAG}")"

  # A retry of the same version/commit reuses the tag and emits the same metadata.
  if [[ "${TAG_COMMIT}" == "${SOURCE_COMMIT}" ]]; then
    mkdir -p "$(dirname "${OUTPUT_FILE}")"

    cat > "${OUTPUT_FILE}" <<METADATA
RELEASE_TAG=${TAG}
SOURCE_COMMIT=${SOURCE_COMMIT}
SOURCE_IMAGE_DIGEST=${SOURCE_IMAGE_DIGEST}
METADATA

    echo "Existing QA release tag found: ${TAG}"
    exit 0
  fi

  # ##*. removes everything through the final dot, leaving the beta counter.
  NUMBER="${TAG##*.}"

  if [[ "${NUMBER}" =~ ^[0-9]+$ ]] && (( NUMBER >= NEXT_NUMBER )); then
    NEXT_NUMBER=$((NUMBER + 1))
  fi
done < <(
  git tag -l "${TAG_PREFIX}*" | sort -V
)

# 4. Validate and push a lightweight tag on the DEV commit, not CI's current HEAD.
RELEASE_TAG="${TAG_PREFIX}${NEXT_NUMBER}"

./ci/release/validate-version.sh \
  "${RELEASE_TAG}" \
  qa

git tag "${RELEASE_TAG}" "${SOURCE_COMMIT}"

# Push only this tag. Concurrent runs choosing the same name for different
# commits fail here rather than moving an existing release tag; rerun to refetch.
git push \
  "https://x-token-auth:${APP_REPO_ACCESS_TOKEN}@bitbucket.org/anovorx/aperture-foundation.git" \
  "${RELEASE_TAG}"

# 5. Write metadata only after the push succeeds. The promotion script sources
# this file and keeps using the original image digest; the tag labels the release.
mkdir -p "$(dirname "${OUTPUT_FILE}")"

cat > "${OUTPUT_FILE}" <<METADATA
RELEASE_TAG=${RELEASE_TAG}
SOURCE_COMMIT=${SOURCE_COMMIT}
SOURCE_IMAGE_DIGEST=${SOURCE_IMAGE_DIGEST}
METADATA

echo "QA release tag created: ${RELEASE_TAG}"
